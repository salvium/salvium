TEST(curve_math, reference_vectors)
{
  for (const auto& v : vectors)
  {
    SCOPED_TRACE(v.name);
    const curve_state_t s = state_of(v.phase, v.reserve, v.sold, v.pool_sal, v.pool_tokens);
    const curve_quote_t q = v.is_buy ? cryptonote::curve_quote_buy(s, v.amount_in, v.min_out)
                                     : cryptonote::curve_quote_sell(s, v.amount_in, v.min_out);
    ASSERT_EQ(q.filled, v.ok);
    ASSERT_EQ(q.amount_out, v.amount_out);
    ASSERT_EQ(q.new_state.phase, v.new_phase);
    ASSERT_EQ(q.new_state.reserve, v.new_reserve);
    ASSERT_EQ(q.new_state.sold, v.new_sold);
    ASSERT_EQ(q.new_state.pool_sal, v.new_pool_sal);
    ASSERT_EQ(q.new_state.pool_tokens, v.new_pool_tokens);
  }
}

TEST(curve_math, fee_rounds_up)
{
  ASSERT_EQ(cryptonote::curve_fee(0), 0u);
  ASSERT_EQ(cryptonote::curve_fee(1), 1u);
  ASSERT_EQ(cryptonote::curve_fee(100), 1u);
  ASSERT_EQ(cryptonote::curve_fee(101), 2u);
  ASSERT_EQ(cryptonote::curve_fee(COIN), COIN / 100);
}

TEST(curve_math, slippage_limit_refunds)
{
  const curve_state_t s;
  const curve_quote_t ok = cryptonote::curve_quote_buy(s, COIN, 0);
  ASSERT_TRUE(ok.filled);
  const curve_quote_t refused = cryptonote::curve_quote_buy(s, COIN, ok.amount_out + 1);
  ASSERT_FALSE(refused.filled);
  ASSERT_EQ(refused.amount_out, 0u);
  ASSERT_TRUE(refused.new_state == s);
  ASSERT_TRUE(cryptonote::curve_quote_buy(s, COIN, ok.amount_out).filled);
}

TEST(curve_math, graduation_has_no_price_jump)
{
  // buy until just before the end of the curve, then cross it in one trade
  const curve_state_t near = cryptonote::curve_quote_buy(curve_state_t(), 29000 * COIN, 0).new_state;
  ASSERT_EQ(near.phase, CURVE_PHASE_CURVE);
  const curve_quote_t cross = cryptonote::curve_quote_buy(near, 3000 * COIN, 0);
  ASSERT_TRUE(cross.filled);
  ASSERT_EQ(cross.new_state.phase, CURVE_PHASE_POOL);
  ASSERT_EQ(cross.new_state.sold, CURVE_SALE_SUPPLY);
  ASSERT_EQ(cryptonote::curve_circulating(cross.new_state), near.sold + cross.amount_out);

  // a curve filled exactly: the pool starts at the curve's final price (within 1 atomic unit)
  const u128 y0 = u128(CURVE_SALE_SUPPLY) + CURVE_VIRTUAL_TOKENS;
  const u128 k0 = y0 * CURVE_VIRTUAL_SAL;
  const u128 x_end = (k0 + CURVE_VIRTUAL_TOKENS - 1) / CURVE_VIRTUAL_TOKENS;
  const uint64_t reserve = (x_end - CURVE_VIRTUAL_SAL).convert_to<uint64_t>();
  const uint64_t curve_final = cryptonote::curve_spot_price(state_of(CURVE_PHASE_CURVE, reserve, CURVE_SALE_SUPPLY));
  const uint64_t pool_start = cryptonote::curve_spot_price(state_of(CURVE_PHASE_POOL, 0, CURVE_SALE_SUPPLY, reserve, CURVE_POOL_SUPPLY));
  ASSERT_LE(curve_final > pool_start ? curve_final - pool_start : pool_start - curve_final, 1u);
}

TEST(curve_math, round_trip_always_loses)
{
  std::mt19937_64 rng(1);
  for (int i = 0; i < 5000; ++i)
  {
    curve_state_t s;
    const uint64_t pre = (rng() % 60000) * COIN;
    if (pre)
    {
      const curve_quote_t q = cryptonote::curve_quote_buy(s, pre, 0);
      if (q.filled)
        s = q.new_state;
    }
    const uint64_t amount = 1 + rng() % (8000 * COIN);
    const curve_quote_t buy = cryptonote::curve_quote_buy(s, amount, 0);
    if (!buy.filled)
      continue;
    const curve_quote_t sell = cryptonote::curve_quote_sell(buy.new_state, buy.amount_out, 0);
    if (!sell.filled)
      continue;
    ASSERT_LT(sell.amount_out, amount);
    ASSERT_TRUE(cryptonote::curve_state_is_solvent(sell.new_state));
  }
}

TEST(curve_math, random_walk_never_pays_out_more_than_burnt)
{
  std::mt19937_64 rng(2);
  for (int run = 0; run < 150; ++run)
  {
    curve_state_t s;
    u128 burnt = 0, paid = 0, last_k = 0;
    uint64_t held = 0;
    for (int step = 0; step < 250; ++step)
    {
      if (held && (rng() % 100) < 40)
      {
        const uint64_t amt = 1 + rng() % held;
        const curve_quote_t q = cryptonote::curve_quote_sell(s, amt, 0);
        if (q.filled)
        {
          paid += q.amount_out;
          held -= amt;
          s = q.new_state;
        }
      }
      else
      {
        const uint64_t amt = 1 + rng() % (9000 * COIN);
        const curve_quote_t q = cryptonote::curve_quote_buy(s, amt, 0);
        if (q.filled)
        {
          burnt += amt;
          held += q.amount_out;
          s = q.new_state;
        }
      }
      ASSERT_TRUE(cryptonote::curve_state_is_solvent(s));
      ASSERT_LE(paid, burnt);
      ASSERT_EQ(cryptonote::curve_circulating(s), held);
      if (s.phase == CURVE_PHASE_POOL)
      {
        const u128 k = u128(s.pool_sal) * s.pool_tokens;
        ASSERT_GE(k, last_k);
        last_k = k;
      }
    }
  }
}

TEST(curve_math, price_is_monotonic_through_graduation)
{
  curve_state_t s;
  uint64_t last = cryptonote::curve_spot_price(s);
  for (int i = 0; i < 400; ++i)
  {
    const curve_quote_t q = cryptonote::curve_quote_buy(s, 900 * COIN, 0);
    if (!q.filled)
      break;
    s = q.new_state;
    const uint64_t p = cryptonote::curve_spot_price(s);
    ASSERT_GE(p, last);
    last = p;
  }
  ASSERT_EQ(s.phase, CURVE_PHASE_POOL);
}

TEST(curve_math, op_from_asset_pair)
{
  using cryptonote::curve_op;
  ASSERT_EQ(cryptonote::get_curve_op("SAL1", "SAL1"), curve_op::LAUNCH);
  ASSERT_EQ(cryptonote::get_curve_op("SAL1", "salPUMP"), curve_op::BUY);
  ASSERT_EQ(cryptonote::get_curve_op("salPUMP", "SAL1"), curve_op::SELL);
  ASSERT_EQ(cryptonote::get_curve_op("SAL", "SAL1"), curve_op::INVALID);
  ASSERT_EQ(cryptonote::get_curve_op("salPUMP", "salDUMP"), curve_op::INVALID);
  ASSERT_EQ(cryptonote::get_curve_op("SAL1", "BURN"), curve_op::INVALID);
}

TEST(curve_math, refund_payout_returns_burnt_asset)
{
  cryptonote::transaction tx;
  tx.type = cryptonote::transaction_type::CURVE;
  tx.source_asset_type = "SAL1";
  tx.destination_asset_type = "salPUMP";
  tx.amount_burnt = 12345;
  curve_quote_t refund;  // filled = false
  uint64_t amount = 0;
  std::string asset;
  cryptonote::curve_payout(tx, refund, amount, asset);
  ASSERT_EQ(amount, 12345u);
  ASSERT_EQ(asset, "SAL1");

  curve_quote_t filled;
  filled.filled = true;
  filled.amount_out = 777;
  cryptonote::curve_payout(tx, filled, amount, asset);
  ASSERT_EQ(amount, 777u);
  ASSERT_EQ(asset, "salPUMP");
}
