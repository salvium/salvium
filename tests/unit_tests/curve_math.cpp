// CURVE bonding-curve math. The vectors are generated by the executable specification:
//   python3 utils/curve_model.py --vectors

#include <random>

#include <boost/multiprecision/cpp_int.hpp>

#include "gtest/gtest.h"

#include "cryptonote_basic/cryptonote_basic.h"
#include "cryptonote_basic/curve.h"
#include "cryptonote_config.h"

using cryptonote::curve_state_t;
using cryptonote::curve_quote_t;

namespace
{
  struct curve_vector
  {
    const char* name;
    bool is_buy;
    uint64_t reserve;
    uint64_t sold;
    uint64_t amount_in;
    bool ok;
    uint64_t amount_out;
    uint64_t new_reserve;
    uint64_t new_sold;
  };

  // generated by: python3 utils/curve_model.py --vectors
  const curve_vector vectors[] = {
    {"buy_from_empty_1_sal", true, 0ull, 0ull, 100000000ull, true, 1062164845680ull, 99000000ull, 1062164845680ull},
    {"buy_from_empty_1000_sal", true, 0ull, 0ull, 100000000000ull, true, 966578707916287ull, 99000000000ull, 966578707916287ull},
    {"buy_dust", true, 0ull, 0ull, 99ull, true, 1051539ull, 98ull, 1051539ull},
    {"buy_min_net", true, 0ull, 0ull, 101ull, true, 1062269ull, 99ull, 1062269ull},
    {"buy_mid_curve", true, 2500000000000ull, 7664285714285714ull, 500000000000ull, true, 379856964062220ull, 2995000000000ull, 8044142678347934ull},
    {"buy_exceeds_supply", true, 0ull, 0ull, 18440000000000000ull, false, 0ull, 0ull, 0ull},
    {"sell_zero_sold", false, 0ull, 0ull, 1ull, false, 0ull, 0ull, 0ull},
    {"sell_partial", false, 2500000000000ull, 7664285714285714ull, 100000000000000ull, true, 109453971119ull, 2389440433213ull, 7564285714285714ull},
    {"sell_all", false, 2500000000000ull, 7664285714285714ull, 7664285714285714ull, true, 2475000000000ull, 0ull, 0ull},
  };

  curve_state_t state_of(uint64_t reserve, uint64_t sold)
  {
    curve_state_t s;
    s.reserve = reserve;
    s.sold = sold;
    return s;
  }
}

TEST(curve_math, reference_vectors)
{
  for (const auto& v : vectors)
  {
    SCOPED_TRACE(v.name);
    const curve_state_t s = state_of(v.reserve, v.sold);
    const curve_quote_t q = v.is_buy ? cryptonote::curve_quote_buy(s, v.amount_in, 0)
                                     : cryptonote::curve_quote_sell(s, v.amount_in, 0);
    ASSERT_EQ(q.filled, v.ok);
    ASSERT_EQ(q.amount_out, v.amount_out);
    ASSERT_EQ(q.new_state.reserve, v.new_reserve);
    ASSERT_EQ(q.new_state.sold, v.new_sold);
  }
}

TEST(curve_math, fee_rounds_up)
{
  ASSERT_EQ(cryptonote::curve_fee(0), 0u);
  ASSERT_EQ(cryptonote::curve_fee(1), 1u);
  ASSERT_EQ(cryptonote::curve_fee(100), 1u);
  ASSERT_EQ(cryptonote::curve_fee(101), 2u);
  ASSERT_EQ(cryptonote::curve_fee(COIN), COIN / 100);
}

TEST(curve_math, slippage_limit_refunds)
{
  const curve_state_t s;
  const curve_quote_t ok = cryptonote::curve_quote_buy(s, COIN, 0);
  ASSERT_TRUE(ok.filled);
  // asking for one more token than the curve gives is a refund, with the state untouched
  const curve_quote_t refused = cryptonote::curve_quote_buy(s, COIN, ok.amount_out + 1);
  ASSERT_FALSE(refused.filled);
  ASSERT_EQ(refused.amount_out, 0u);
  ASSERT_TRUE(refused.new_state == s);
  // the exact amount is accepted
  ASSERT_TRUE(cryptonote::curve_quote_buy(s, COIN, ok.amount_out).filled);
}

TEST(curve_math, round_trip_always_loses)
{
  std::mt19937_64 rng(1);
  for (int i = 0; i < 5000; ++i)
  {
    curve_state_t s;
    const uint64_t pre = (rng() % 50000) * COIN;
    if (pre)
    {
      const curve_quote_t q = cryptonote::curve_quote_buy(s, pre, 0);
      if (q.filled)
        s = q.new_state;
    }
    const uint64_t amount = 1 + rng() % (5000 * COIN);
    const curve_quote_t buy = cryptonote::curve_quote_buy(s, amount, 0);
    if (!buy.filled)
      continue;
    const curve_quote_t sell = cryptonote::curve_quote_sell(buy.new_state, buy.amount_out, 0);
    ASSERT_TRUE(sell.filled);
    ASSERT_LT(sell.amount_out, amount);
    ASSERT_EQ(sell.new_state.sold, s.sold);
    ASSERT_GE(sell.new_state.reserve, s.reserve);
    ASSERT_TRUE(cryptonote::curve_state_is_solvent(sell.new_state));
  }
}

TEST(curve_math, random_walk_never_pays_out_more_than_burnt)
{
  std::mt19937_64 rng(2);
  for (int run = 0; run < 100; ++run)
  {
    curve_state_t s;
    boost::multiprecision::uint128_t burnt = 0, paid = 0;
    uint64_t held = 0;
    for (int step = 0; step < 200; ++step)
    {
      if (held && (rng() % 100) < 45)
      {
        const uint64_t amt = 1 + rng() % held;
        const curve_quote_t q = cryptonote::curve_quote_sell(s, amt, 0);
        if (q.filled)
        {
          paid += q.amount_out;
          held -= amt;
          s = q.new_state;
        }
      }
      else
      {
        const uint64_t amt = 1 + rng() % (20000 * COIN);
        const curve_quote_t q = cryptonote::curve_quote_buy(s, amt, 0);
        if (q.filled)
        {
          burnt += amt;
          held += q.amount_out;
          s = q.new_state;
        }
      }
      ASSERT_TRUE(cryptonote::curve_state_is_solvent(s));
      ASSERT_LE(paid + s.reserve, burnt);
    }
    ASSERT_EQ(s.sold, held);
  }
}

TEST(curve_math, price_is_monotonic)
{
  curve_state_t s;
  uint64_t last = cryptonote::curve_spot_price(s);
  for (int i = 0; i < 500; ++i)
  {
    const curve_quote_t q = cryptonote::curve_quote_buy(s, 1000 * COIN, 0);
    if (!q.filled)
      break;
    s = q.new_state;
    const uint64_t p = cryptonote::curve_spot_price(s);
    ASSERT_GE(p, last);
    last = p;
  }
}

TEST(curve_math, op_from_asset_pair)
{
  using cryptonote::curve_op;
  ASSERT_EQ(cryptonote::get_curve_op("SAL1", "SAL1"), curve_op::LAUNCH);
  ASSERT_EQ(cryptonote::get_curve_op("SAL1", "salPUMP"), curve_op::BUY);
  ASSERT_EQ(cryptonote::get_curve_op("salPUMP", "SAL1"), curve_op::SELL);
  ASSERT_EQ(cryptonote::get_curve_op("SAL", "SAL1"), curve_op::INVALID);
  ASSERT_EQ(cryptonote::get_curve_op("salPUMP", "salDUMP"), curve_op::INVALID);
  ASSERT_EQ(cryptonote::get_curve_op("SAL1", "BURN"), curve_op::INVALID);
}

TEST(curve_math, refund_payout_returns_burnt_asset)
{
  cryptonote::transaction tx;
  tx.type = cryptonote::transaction_type::CURVE;
  tx.source_asset_type = "SAL1";
  tx.destination_asset_type = "salPUMP";
  tx.amount_burnt = 12345;
  curve_quote_t refund;  // filled = false
  uint64_t amount = 0;
  std::string asset;
  cryptonote::curve_payout(tx, refund, amount, asset);
  ASSERT_EQ(amount, 12345u);
  ASSERT_EQ(asset, "SAL1");

  curve_quote_t filled;
  filled.filled = true;
  filled.amount_out = 777;
  cryptonote::curve_payout(tx, filled, amount, asset);
  ASSERT_EQ(amount, 777u);
  ASSERT_EQ(asset, "salPUMP");
}
